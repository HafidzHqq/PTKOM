// Helper to convert RawFoodItemInput into a validated FoodItem with backward-compatible aliases
function enrichFoodItem(raw: RawFoodItemInput): FoodItem {
  const avgPrice = Math.round((raw.priceRange.min + raw.priceRange.max) / 2);
  const enriched = {
    ...raw,
    avg_price_idr: avgPrice,
    calories: raw.nutrition.kcal,
    protein_g: raw.nutrition.protein,
    fat_g: raw.nutrition.fat,
    carbs_g: raw.nutrition.carbs,
    fiber_g: raw.nutrition.fiber ?? 0,
    availability: raw.venue,
    is_budget_friendly: raw.priceRange.max <= 15000,
  };

  return foodItemSchema.parse(enriched);
}

